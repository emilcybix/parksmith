export const MAP_BY_ID: ReadonlyMap<MapId, ShippedMapDefinition> = new Map(MAPS.map((definition) => [definition.id, definition]));

export const DEFAULT_MAP_ID: MapId = 'meadow';

export const isMapId = (value: unknown): value is MapId => (
  typeof value === 'string' && MAP_BY_ID.has(value as MapId)
);

/** The maps of one biome, in picker order. */
export const mapsOfBiome = (biome: MapDefinition['biome']): readonly ShippedMapDefinition[] => (
  MAPS.filter((definition) => definition.biome === biome)
);
