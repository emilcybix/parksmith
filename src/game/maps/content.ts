import type { MapDefinition, MapId, ShippedMapDefinition } from './types';

/**
 * The hand-authored maps: seven 32 x 32 maps (Phase 24 step 1), wholly owned, and the 64 x 64 estates of Phase 21, which
 * start with a small owned area around the gate (the rest is for sale parcel by parcel). Rows are ASCII, x = column left to right,
 * y = row top to bottom, north is up. Legend (see parse.ts): '.' base ground, ',' alt ground, '~' water,
 * 'E' the gate, T t b R s = 1x1 props per the biome legend, L = a 2x1 log (a pair), # = a 1x1 permanent
 * prop, X = a 2x2 permanent prop (four X in a square). Prop ids follow row-major order of the anchor cell.
 *
 * Every map keeps the First Day apron (the six lanes beside the gate, eleven cells deep) free of props and
 * water, so the scripted First Day route exists on all of them, and a connected open area reachable
 * from the gate without spending anything (validate.ts; the data test pins the numbers).
 */

